#!/usr/bin/env python3
"""Generate formal/jtag_fsm_arcs.svh from the state table in docs/design_spec.md.

One assertion and one cover per arc (16 states x 2 TMS values = 32 arcs),
plus one cover per state. The table is parsed from the spec, not from the
RTL, so the checks stay independent of the code they check. The state codes
are cross-checked against rtl/jtag_pkg.sv so the two cannot drift apart.

Usage (from the repo root):
    python3 scripts/gen_fsm_props.py            # write the .svh
    python3 scripts/gen_fsm_props.py --check    # exit 1 if the .svh is stale
"""
import re
import sys
from pathlib import Path

SPEC = Path("docs/design_spec.md")
PKG = Path("rtl/jtag_pkg.sv")
OUT = Path("formal/jtag_fsm_arcs.svh")

ROW = re.compile(r"^\|\s*([A-Z0-9_]+)\s*\|\s*`([0-9A-F])`\s*\|\s*([A-Z0-9_]+)\s*\|\s*([A-Z0-9_]+)\s*\|\s*$")
ENUM = re.compile(r"^\s*([A-Z0-9_]+)\s*=\s*4'h([0-9A-F])\s*,?\s*$")


def die(msg):
    sys.exit(f"gen_fsm_props: {msg}")


def parse_spec():
    """Return [(state, code, next_tms0, next_tms1)] from the spec's state table."""
    rows = [m.groups() for m in map(ROW.match, SPEC.read_text(encoding="utf-8").splitlines()) if m]
    if len(rows) != 16:
        die(f"expected 16 rows in the state table of {SPEC}, found {len(rows)}")
    states = [r[0] for r in rows]
    if len(set(states)) != 16:
        die("duplicate state in the state table")
    for state, _, n0, n1 in rows:
        for nxt in (n0, n1):
            if nxt not in states:
                die(f"{state}: next state {nxt} is not a state")
    if len({r[1] for r in rows}) != 16:
        die("duplicate state code in the state table")
    return rows


def check_codes(rows):
    """The spec's codes must match tap_state_e in the RTL package."""
    pkg = {m.group(1): m.group(2) for m in map(ENUM.match, PKG.read_text(encoding="utf-8").splitlines()) if m}
    for state, code, _, _ in rows:
        if pkg.get(state) != code:
            die(f"{state}: spec code {code}, jtag_pkg.sv code {pkg.get(state)}")


def render(rows):
    out = [
        "// Generated by scripts/gen_fsm_props.py from the state table in docs/design_spec.md.",
        "// Do not edit: change the spec and re-run the script.",
        "// Included into jtag_tap_fsm_props.sv: uses its default clocking and disable iff.",
        "",
        "// Per-arc assertions (R1)",
    ]
    for state, _, n0, n1 in rows:
        for tms, nxt in (("0", n0), ("1", n1)):
            neg = "!" if tms == "0" else " "
            out.append(f"a_arc_{state.lower()}_{tms}: assert property ("
                       f"(state == {state} && {neg}tms) |=> state == {nxt});")
    out += ["", "// Per-arc covers: every transition is taken"]
    for state, _, n0, n1 in rows:
        for tms, nxt in (("0", n0), ("1", n1)):
            neg = "!" if tms == "0" else " "
            out.append(f"c_arc_{state.lower()}_{tms}: cover property ("
                       f"(state == {state} && {neg}tms) ##1 state == {nxt});")
    out += ["", "// Per-state covers: every state is reached"]
    for state, _, _, _ in rows:
        out.append(f"c_state_{state.lower()}: cover property (state == {state});")
    return "\n".join(out) + "\n"


def main():
    rows = parse_spec()
    check_codes(rows)
    text = render(rows)
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            die(f"{OUT} is stale: run python3 scripts/gen_fsm_props.py")
        return
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}: 32 arc assertions, 32 arc covers, 16 state covers")


if __name__ == "__main__":
    main()
